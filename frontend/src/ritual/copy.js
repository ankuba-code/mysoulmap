export const QUESTION_IDS = ["q0", "q1", "q2", "q3", "q4", "q5", "q6", "q7"];

export function ritualCopy(language) {
  const lang = UI[language] ? language : "de";
  return {
    ...UI.de,
    ...UI[lang],
    reasons: REASONS[lang] || REASONS.de,
    questions: QUESTIONS[lang] || QUESTIONS.de,
  };
}

export function reasonText(copy, reason, place, card) {
  const dimension = reason?.dimension;
  const key =
    dimension === "element"
      ? place?.element && card?.element && place.element === card.element
        ? "element_match"
        : "element_contrast"
      : dimension;
  const template = copy.reasons?.[key];
  if (!template) {
    return reason?.text || "";
  }
  return template.replace("{element}", ritualWord(copy, place?.element || card?.element || ""));
}

export function ritualWord(copy, value) {
  if (value == null || value === "") {
    return "";
  }
  const key = String(value);
  return copy.words?.[key] || key;
}

export function ritualLines(answers, language = "de") {
  const pack = QUESTIONS[language] || QUESTIONS.de;
  return QUESTION_IDS.map((id) => {
    const question = pack[id];
    const value = answers?.[id];
    if (!question) {
      return null;
    }
    if (Array.isArray(question.choices) && Number.isInteger(value) && question.choices[value]) {
      return `${question.text} ${question.choices[value]}`;
    }
    if (typeof value === "string" && value.trim()) {
      return `${question.text} ${value.trim()}`;
    }
    return null;
  }).filter(Boolean);
}
